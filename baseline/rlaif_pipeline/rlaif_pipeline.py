"""
Wraps simulator.py and judge.py into a Best-of-2 loop:
  For each example:
    1. Run 2 independent conversations (Mistral agent <-> Gemini simulator)
    2. Judge both with Gemini judge
    3. Keep the higher-scoring conversation
    4. Save to output dataset for PPO/DPO : basic reward model for baseline in this instance

Checkpoint and Resume:
  - Saves progress to GCS every CHECKPOINT_EVERY examples
  - On restart, automatically resumes from last checkpoint

flags to be used on vertex-ai while scheduling a custom job
--project=274690076649
--bucket=rlaif-data-bucket-rlaif-project
--data_blob=airdialogue_sampled_5k.jsonl
--model_prefix=models/sft-mistral-v6-1-epoch
--max_samples=10
--gemini_version=gemini-2.5-flash
--overwrite
--ppo

============================================
--project=274690076649
--bucket=rlaif-data-bucket-rlaif-project
--data_blob=airdialogue_sampled_5k.jsonl
--model_prefix=models/sft-mistral-20k-v3-2epoch
--max_samples=5
--gemini_version=gemini-2.5-flash
--overwrite
--ppo
"""


import os
import json
import logging
import argparse
import time
from datetime import datetime, timezone
 
import vertexai
from vertexai.generative_models import GenerativeModel, GenerationConfig
from google.cloud import storage
from simulator import load_agent, run_conversation
from judge import score_transcript
from config import (
    CHECKPOINT_EVERY,
    N_CANDIDATES,
    CHECKPOINT_LOCAL,
    CHECKPOINT_BLOB,
    OUTPUT_LOCAL,
    OUTPUT_BLOB,
)
from utils import (
    get_secret,
    download_from_gcs,
    download_dir_from_gcs,
    upload_to_gcs,
    save_checkpoint,
    load_checkpoint,
)
from ppo_trainer import PPOTrainer
from transformers import AutoModelForCausalLM
 
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
logger = logging.getLogger(__name__)
 
 
def main(args):
    logger.info("Fetching secrets ...")
    hf_token = get_secret(args.project, "hf-token")
    os.environ["HF_TOKEN"]               = hf_token
    os.environ["HUGGING_FACE_HUB_TOKEN"] = hf_token
 
    vertexai.init(project="rlaif-project", location="us-central1")
 
    simulator_gemini = GenerativeModel(
        args.gemini_version,
        generation_config=GenerationConfig(
            temperature=0.8,
            max_output_tokens=512,
        ),
    )
    judge_gemini = GenerativeModel(
        args.gemini_version,
        generation_config=GenerationConfig(
            temperature=0.0,
            max_output_tokens=4096,   # must be large enough for full reasoning block!!! Revisit again to fix the issue of truncation!
            response_mime_type="application/json",
        ),
    )
    logger.info("Gemini ready — simulator(temp=0.8), judge(temp=0.0)")
 
    local_adapter = "/tmp/agent_model"
    logger.info(f"Downloading adapter from gs://{args.bucket}/{args.model_prefix} ...")
    download_dir_from_gcs(args.bucket, args.model_prefix, local_adapter)
 
    agent_model, agent_tokenizer = load_agent(
        model_path=local_adapter,
        base_model_id=args.base_model_id,
    )
 
    ppo_trainer = None

    if args.ppo:
        logger.info("PPO enabled — loading frozen reference model ...")
        from transformers import BitsAndBytesConfig
        import torch
 
        bnb_cfg = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.bfloat16,
            bnb_4bit_use_double_quant=True,
        )

        ref_model = AutoModelForCausalLM.from_pretrained(
            args.base_model_id,
            quantization_config=bnb_cfg,
            device_map={"": 0},
            trust_remote_code=True,
        )

        ref_model.eval()
        ppo_trainer = PPOTrainer(
            agent_model=agent_model,
            ref_model=ref_model,
            tokenizer=agent_tokenizer,
            device="cuda",
        )
        logger.info("PPOTrainer initialised.")
 
    # Logged once at startup so it appears clearly in Cloud Logging
    logger.info("=" * 70)
    logger.info("RL TRAINING SETUP")
    logger.info("  Algorithm : PPO (Proximal Policy Optimisation)")
    logger.info("  Policy : Mistral-7B + LoRA adapter (4-bit quantized)")
    logger.info("  Reference model : Frozen SFT checkpoint (same base)")
    logger.info("  STATE : Full conversation history + available flights KB")
    logger.info(" (tokenized Mistral instruct prompt, up to context limit)")
    logger.info("  ACTION : Agent utterance — next tokens generated by policy")
    logger.info(" (greedy decode, max 128 tokens, hard sentence cutoff)")
    logger.info("  REWARD : Gemini judge score 1-10 → normalised to [-1, +1]")
    logger.info(" 10=perfect booking, 1=hallucination/constraint violation")
    logger.info(" Normalisation: r = (score - 5.5) / 4.5")
    logger.info("  CREDIT ASSIGN : Discounted per-token reward (gamma=0.99)")
    logger.info("  ADVANTAGE : Normalised discounted reward (zero mean, unit std)")
    logger.info("  PPO CLIP : epsilon=0.2 (ratio clamped to [0.8, 1.2])")
    logger.info("  GRAD ACCUM : 10 episodes before optimizer step")
    logger.info("  POLICY LR : 1e-5 (AdamW)")
    logger.info("  VALUE LR : 1e-5 (AdamW, separate optimizer)")
    logger.info("  POLICY CLIP : grad_norm max 1.0")
    logger.info("  VALUE CLIP : grad_norm max 0.1 (tight — prevents value explosion)")
    logger.info("  KL COEF : 0.05 (entropy penalty to prevent policy collapse)")
    logger.info("  SIMULATOR : Gemini 2.5 Flash (temp=0.8) — plays fake customer")
    logger.info("  JUDGE : Gemini 2.5 Flash (temp=0.0) — scores finished transcript")
    logger.info("=" * 70)
 
    local_data = "/tmp/train.jsonl"
    download_from_gcs(args.bucket, args.data_blob, local_data)
 
    rows = []
    with open(local_data) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
 
    if args.max_samples:
        rows = rows[:args.max_samples]
 
    logger.info(f"Loaded {len(rows)} examples")
 
    if args.overwrite:
        logger.info("Overwrite flag detected! Deleting existing GCS checkpoints...")
        storage_client = storage.Client(project=args.project)
        gcs_bucket     = storage_client.bucket(args.bucket)
        for blob_name in [CHECKPOINT_BLOB, OUTPUT_BLOB]:
            blob = gcs_bucket.blob(blob_name)
            if blob.exists():
                blob.delete()
                logger.info(f"  Deleted {blob_name}")
 
    checkpoint = load_checkpoint(args.bucket)
    if checkpoint:
        processed_indices = set(checkpoint["processed_indices"])
        all_scores = checkpoint["scores"]
    else:
        processed_indices = set()
        all_scores = []

    output_file   = open(OUTPUT_LOCAL, "a" if checkpoint else "w")
    example_count = len(processed_indices)
 
    logger.info("─" * 60)
    logger.info(f"RLAIF pipeline — single response + PPO")
    logger.info(f"  Total   : {len(rows)}")
    logger.info(f"  Done    : {example_count}")
    logger.info(f"  Left    : {len(rows) - example_count}")
    logger.info("─" * 60)
 
    for idx, row in enumerate(rows):
 
        if idx in processed_indices:
            continue
 
        intent = row.get("intent", {})
        kb = row.get("kb", [])
 
        if not intent or not kb:
            logger.warning(f"Row {idx} — missing intent or KB, skipping")
            processed_indices.add(idx)
            continue
 
        logger.info(f"\n[{idx+1}/{len(rows)}] Running conversation ...")
 
        # Single conversation
        try:
            result = run_conversation(
                row=row,
                agent_model=agent_model,
                agent_tokenizer=agent_tokenizer,
                gemini_model=simulator_gemini,
                max_turns=args.max_turns,
            )
        except Exception as e:
            logger.error(f"  Conversation failed: {e}")
            processed_indices.add(idx)
            continue
 
        # Judge scores it 1-10
        transcript_row = {
            "intent":     result["intent"],
            "kb":         result["kb"],
            "transcript": result["transcript"],
            "outcome":    result["outcome"],
        }
 
        try:
            judgment = score_transcript(judge_gemini, transcript_row)
            score    = judgment.get("score", 5)
            logger.info(
                f"  Score: {score}/10 | "
                f"outcome: {judgment.get('outcome', '?')} | "
                f"{judgment.get('justification', '')[:80]}"
            )
        except Exception as e:
            logger.error(f"  Judge failed: {e}")
            score    = 5
            judgment = {"score": 5, "outcome": "judge_error", "error": True}
 
        n_turns     = result.get("num_turns", 0)
        n_tokens    = sum(len(ids) for ids in (result.get("token_ids") or []))
        reward_norm = round((float(score) - 5.5) / 4.5, 4)
        logger.info(
            f"[RL EPISODE {idx+1}] "
            f"STATE=conversation({n_turns} turns, KB={len(kb)} flights) | "
            f"ACTION={n_tokens} tokens generated | "
            f"REWARD={score}/10 → {reward_norm:+.4f} normalised | "
            f"OUTCOME={judgment.get('outcome','?')}"
        )
 
        # PPO update!
        if args.ppo and ppo_trainer is not None:
            try:
                ppo_metrics = ppo_trainer.step(
                    episode_logprobs=result["logprobs"],
                    reward=score,
                    input_ids_list=result.get("token_ids"),
                )
                logger.info(f"  PPO: {ppo_metrics}")
            except Exception as e:
                logger.error(f"  PPO step failed: {e}")
 
        all_scores.append(score)
 
        record = {
            "idx": idx,
            "intent": intent,
            "kb": kb,
            "score": score,
            "transcript": result["transcript"],
            "outcome": judgment.get("outcome", "unknown"),
            "judgment": judgment,
            "num_turns": result["num_turns"],
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }
        output_file.write(json.dumps(record) + "\n")
        output_file.flush()
 
        processed_indices.add(idx)
        example_count += 1
 
        if example_count % CHECKPOINT_EVERY == 0:
            save_checkpoint(
                args.bucket,
                list(processed_indices),
                all_scores,
                example_count,
            )
 
        time.sleep(1.5)
 
    output_file.close()
 
    if args.ppo and ppo_trainer is not None:
        ppo_trainer.flush()
        ppo_trainer.save(args.ppo_save_path)
        logger.info("Uploading PPO adapter to GCS ...")
        gcs_prefix = f"models/ppo-mistral-{datetime.now(timezone.utc).strftime('%Y%m%d-%H%M')}"
        for fname in os.listdir(args.ppo_save_path):
            local_file = os.path.join(args.ppo_save_path, fname)
            if os.path.isfile(local_file):
                upload_to_gcs(args.bucket, local_file, f"{gcs_prefix}/{fname}")
                logger.info(f"  Uploaded {fname}")
        logger.info(f"PPO adapter saved to gs://{args.bucket}/{gcs_prefix}/")
 
    logger.info("Uploading final output ...")
    upload_to_gcs(args.bucket, OUTPUT_LOCAL, OUTPUT_BLOB)
    save_checkpoint(args.bucket, list(processed_indices), all_scores, example_count)
 
    if all_scores:
        n = len(all_scores)
        avg = sum(all_scores) / n
        excellent = sum(1 for s in all_scores if s >= 8)
        good = sum(1 for s in all_scores if 6 <= s < 8)
        average   = sum(1 for s in all_scores if 4 <= s < 6)
        poor = sum(1 for s in all_scores if s < 4)
 
        logger.info("=" * 60)
        logger.info("PIPELINE COMPLETE")
        logger.info(f"  Examples processed : {n}")
        logger.info(f"  Average score : {avg:.2f} / 10")
        logger.info(f"  Excellent  (8-10)  : {excellent}  ({100*excellent/n:.1f}%)")
        logger.info(f"  Good (6-7) : {good} ({100*good/n:.1f}%)")
        logger.info(f"  Average (4-5)   : {average} ({100*average/n:.1f}%)")
        logger.info(f"  Poor (1-3)   : {poor} ({100*poor/n:.1f}%)")
        logger.info(f"  Output : gs://{args.bucket}/{OUTPUT_BLOB}")
        logger.info("=" * 60)
 
 
if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="RLAIF pipeline — single response + PPO")
    parser.add_argument("--project",        required=True)
    parser.add_argument("--bucket",         required=True)
    parser.add_argument("--data_blob",      required=True)
    parser.add_argument("--model_prefix",   default="models/sft-mistral-baseline")
    parser.add_argument("--base_model_id",  default="mistralai/Mistral-7B-v0.1")
    parser.add_argument("--max_turns",      type=int, default=10)
    parser.add_argument("--max_samples",    type=int, default=None)
    parser.add_argument("--gemini_version", type=str, default="gemini-2.5-flash")
    parser.add_argument("--overwrite",      action="store_true")
    parser.add_argument("--ppo",            action="store_true")
    parser.add_argument("--ppo_save_path",  type=str, default="/tmp/ppo_adapter")
    args = parser.parse_args()
    main(args)